def get_lang():
    return session.get("lang", DEFAULT)


def t(key, lang=None):
    lang = lang or get_lang()
    pair = T.get(key)
    if not pair:
        return key
    return pair[1] if lang == "ar" else pair[0]


def is_rtl(lang=None):
    return (lang or get_lang()) == "ar"


